-- Local Pokémon catalogue: base data synchronised from PokeAPI plus fields owned by this app.

CREATE TABLE pokemon (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pokeapi_id    INTEGER      NOT NULL UNIQUE,
    name          VARCHAR(100) NOT NULL,
    sprite_url    VARCHAR(500),
    category      VARCHAR(200),
    height        INTEGER,
    weight        INTEGER,
    local_name    VARCHAR(100),
    region        VARCHAR(100),
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_pokemon_lower_name ON pokemon (LOWER(name));

CREATE TABLE pokemon_type (
    pokemon_id BIGINT      NOT NULL REFERENCES pokemon (id) ON DELETE CASCADE,
    position   INTEGER     NOT NULL,
    name       VARCHAR(50) NOT NULL,
    slot       INTEGER     NOT NULL,
    PRIMARY KEY (pokemon_id, position)
);

CREATE TABLE pokemon_ability (
    pokemon_id BIGINT       NOT NULL REFERENCES pokemon (id) ON DELETE CASCADE,
    position   INTEGER      NOT NULL,
    name       VARCHAR(100) NOT NULL,
    hidden     BOOLEAN      NOT NULL,
    PRIMARY KEY (pokemon_id, position)
);

CREATE TABLE pokemon_tag (
    pokemon_id BIGINT      NOT NULL REFERENCES pokemon (id) ON DELETE CASCADE,
    position   INTEGER     NOT NULL,
    tag        VARCHAR(30) NOT NULL,
    PRIMARY KEY (pokemon_id, position)
);
